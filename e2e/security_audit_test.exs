defmodule E2eAppWeb.SecurityAuditTest do
  @moduledoc """
  Offensive security probes against the authentication generated by `absinthe_initializer`.

  Every test encodes the *secure* expected behaviour. A failing test is a security finding.
  """

  use E2eAppWeb.ConnCase, async: false

  alias E2eApp.Accounts
  alias E2eApp.Accounts.{User, UserToken}
  alias E2eApp.Repo

  @cookie "_e2e_app_session"
  @password "super_secure_password_123"
  @rate_limited "Too many requests. Please try again later."

  @sign_in_vars """
  mutation SignIn($email: String!, $password: String!) {
    signIn(email: $email, password: $password) { token user { email } }
  }
  """

  @sign_up_vars """
  mutation SignUp($email: String!, $password: String!) {
    signUp(email: $email, password: $password) { token user { email } }
  }
  """

  @me "query { me { email isAdmin } }"

  setup do
    original = Application.get_env(:e2e_app, E2eApp.Auth)

    on_exit(fn ->
      if original do
        Application.put_env(:e2e_app, E2eApp.Auth, original)
      else
        Application.delete_env(:e2e_app, E2eApp.Auth)
      end
    end)

    :ok
  end

  defp conn_ip do
    %{build_conn() | remote_ip: {172, 16, :rand.uniform(250), :rand.uniform(250)}}
  end

  defp gql(conn, query, variables \\ %{}) do
    conn
    |> put_req_header("content-type", "application/json")
    |> post("/api", Jason.encode!(%{query: query, variables: variables}))
  end

  defp sign_in_doc(email, password) do
    ~s|mutation { signIn(email: "#{email}", password: "#{password}") { user { email } } }|
  end

  defp error_messages(conn) do
    case Jason.decode(conn.resp_body) do
      {:ok, %{"errors" => errors}} -> Enum.map(errors, & &1["message"])
      _ -> []
    end
  end

  defp put_auth_config(overrides) do
    base = [
      transport: :both,
      cache: :ets,
      rate_limit: [enabled: true, max_requests: 10, invalid_token_max_requests: 20, window_seconds: 60]
    ]

    Application.put_env(:e2e_app, E2eApp.Auth, Keyword.merge(base, overrides))
  end

  describe "CSRF" do
    test "SEC-01 login CSRF: cross-site urlencoded form cannot sign in and plant a session cookie" do
      {:ok, _} = Accounts.register_user(%{email: "attacker1@example.com", password: @password})

      conn =
        conn_ip()
        |> put_req_header("content-type", "application/x-www-form-urlencoded")
        |> post("/api", URI.encode_query(%{query: sign_in_doc("attacker1@example.com", @password)}))

      refute Map.has_key?(conn.resp_cookies, @cookie),
             "attacker session cookie was planted via cross-site form POST"

      refute conn.resp_body =~ "attacker1@example.com"
    end

    test "SEC-02 login CSRF: no-cors text/plain POST with query string cannot sign in" do
      {:ok, _} = Accounts.register_user(%{email: "attacker2@example.com", password: @password})
      query = URI.encode_query(%{query: sign_in_doc("attacker2@example.com", @password)})

      conn =
        conn_ip()
        |> put_req_header("content-type", "text/plain")
        |> post("/api?" <> query, "")

      refute Map.has_key?(conn.resp_cookies, @cookie),
             "attacker session cookie was planted via no-cors text/plain POST"
    end

    test "SEC-03 mutations cannot be executed over GET" do
      doc = ~s|mutation { signUp(email: "viaget@example.com", password: "#{@password}") { token } }|
      conn = conn_ip() |> get("/api", %{query: doc})

      assert Repo.get_by(User, email: "viaget@example.com") == nil
      refute Map.has_key?(conn.resp_cookies, @cookie)
    end

    test "SEC-04 a garbage Bearer header cannot fall back to a cross-site cookie" do
      {:ok, user} = Accounts.register_user(%{email: "bypass@example.com", password: @password})
      token = Accounts.generate_user_session_token(user)

      conn =
        conn_ip()
        |> put_req_header("sec-fetch-site", "cross-site")
        |> put_req_header("authorization", "Bearer garbage")
        |> put_req_cookie(@cookie, token)
        |> gql(@me)

      refute conn.resp_body =~ "bypass@example.com"
    end
  end

  describe "Brute force and DoS" do
    test "SEC-05 aliased signIn brute force inside one request is rate limited per attempt" do
      put_auth_config(rate_limit: [enabled: true, max_requests: 3, window_seconds: 60])

      aliases =
        Enum.map_join(1..10, "\n", fn i ->
          ~s|a#{i}: signIn(email: "alias_victim@example.com", password: "wrong_password_#{i}") { token }|
        end)

      conn = conn_ip() |> gql("mutation { #{aliases} }")
      limited = Enum.count(error_messages(conn), &(&1 == @rate_limited))

      assert limited >= 7, "only #{limited}/10 aliased attempts were rate limited"
    end

    test "SEC-06 rate limiter buckets do not retain attacker-controlled payloads" do
      put_auth_config(rate_limit: [enabled: true, max_requests: 100, window_seconds: 60])
      huge_email = String.duplicate("a", 100_000) <> "@example.com"

      conn_ip() |> gql(@sign_in_vars, %{email: huge_email, password: "wrong_password_123"})

      largest =
        E2eApp.Auth.RateLimiter
        |> :ets.tab2list()
        |> Enum.map(&:erlang.external_size/1)
        |> Enum.max()

      assert largest < 2_000, "a single rate-limit bucket retains #{largest} bytes"
    end

    test "SEC-07 batched GraphQL requests cannot multiply work past the complexity limit" do
      batch = for _ <- 1..50, do: %{query: "query { __typename }"}

      conn =
        conn_ip()
        |> put_req_header("content-type", "application/json")
        |> post("/api", Jason.encode!(batch))

      refute match?({:ok, results} when is_list(results) and length(results) == 50,
                    Jason.decode(conn.resp_body)),
             "server executed 50 batched operations in a single request"
    end
  end

  describe "Account integrity" do
    test "SEC-08 schema rejects privilege escalation through an isAdmin argument" do
      doc =
        ~s|mutation { signUp(email: "escalate@example.com", password: "#{@password}", isAdmin: true) { user { isAdmin } } }|

      conn = conn_ip() |> gql(doc)

      assert Enum.any?(error_messages(conn), &(&1 =~ "isAdmin"))
      assert Repo.get_by(User, email: "escalate@example.com") == nil
    end

    test "SEC-09 email uniqueness is case-insensitive (no account shadowing)" do
      {:ok, _} = Accounts.register_user(%{email: "Shadow@Example.com", password: @password})

      conn = conn_ip() |> gql(@sign_up_vars, %{email: "shadow@example.com", password: @password})

      assert "Could not create account." in error_messages(conn)

      assert Repo.all(User)
             |> Enum.count(&(String.downcase(&1.email) == "shadow@example.com")) == 1
    end

    test "SEC-10 session tokens carry 256 bits of entropy and are never stored in plaintext" do
      {:ok, user} = Accounts.register_user(%{email: "entropy@example.com", password: @password})
      token = Accounts.generate_user_session_token(user)
      {:ok, raw} = Base.url_decode64(token, padding: false)

      assert byte_size(raw) == 32
      assert Repo.get_by(UserToken, token: raw) == nil
      assert Repo.get_by(UserToken, token: :crypto.hash(:sha256, raw))
    end

    test "SEC-11 password change revokes every existing session" do
      {:ok, user} = Accounts.register_user(%{email: "rotate@example.com", password: @password})
      token = Accounts.generate_user_session_token(user)
      new_password = "another_secure_password_456"

      {:ok, _} =
        Accounts.update_user_password(user, @password, %{
          password: new_password,
          password_confirmation: new_password
        })

      conn = conn_ip() |> put_req_header("authorization", "Bearer #{token}") |> gql(@me)
      assert "The session is invalid or expired." in error_messages(conn)
    end

    test "SEC-12 out-of-band revocation is honoured once the cache TTL elapses" do
      put_auth_config(cache_ttl_seconds: 1)

      {:ok, user} = Accounts.register_user(%{email: "oob@example.com", password: @password})
      token = Accounts.generate_user_session_token(user)

      Repo.delete_all(UserToken)
      Process.sleep(2_100)

      conn = conn_ip() |> put_req_header("authorization", "Bearer #{token}") |> gql(@me)
      assert "The session is invalid or expired." in error_messages(conn)
    end
  end
end
